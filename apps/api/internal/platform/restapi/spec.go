package restapi

import (
	"bytes"
	"fmt"

	"github.com/danielgtaylor/huma/v2"
)

// specHeader opens the committed spec, so nobody edits it by hand; CI fails when it differs from
// what the code generates.
const specHeader = "# Generated by cmd/openapi from the Go registrations (ADR-0018). Do not edit.\n"

// Spec renders the OpenAPI document of api as YAML, the content of packages/openapi/openapi.yaml.
// It first removes two things Huma adds that the API does not mean, in place on api's document:
//
//   - additionalProperties: false on every object. Huma would reject unknown members when it
//     validates a body, but validation stays in the domain, which ignores them; the spec must
//     not promise a rejection that never happens.
//   - a parameter schema's description when it repeats the parameter's own description: Huma
//     copies the doc tag onto both.
func Spec(api huma.API) ([]byte, error) {
	oapi := api.OpenAPI()
	for _, s := range oapi.Components.Schemas.Map() {
		allowAdditionalProperties(s)
	}
	for _, item := range oapi.Paths {
		for _, op := range []*huma.Operation{item.Get, item.Put, item.Post, item.Delete, item.Patch} {
			if op == nil {
				continue
			}
			for _, p := range op.Parameters {
				if p.Schema != nil && p.Schema.Description == p.Description {
					p.Schema.Description = ""
				}
			}
		}
	}
	y, err := oapi.YAML()
	if err != nil {
		return nil, fmt.Errorf("render spec: %w", err)
	}
	var b bytes.Buffer
	b.WriteString(specHeader)
	b.Write(y)
	return b.Bytes(), nil
}

// allowAdditionalProperties removes additionalProperties: false from s and every schema inside it.
// A schema for additional values, as in Metadata, stays.
func allowAdditionalProperties(s *huma.Schema) {
	if s == nil {
		return
	}
	if allowed, ok := s.AdditionalProperties.(bool); ok && !allowed {
		s.AdditionalProperties = nil
	}
	if inner, ok := s.AdditionalProperties.(*huma.Schema); ok {
		allowAdditionalProperties(inner)
	}
	for _, p := range s.Properties {
		allowAdditionalProperties(p)
	}
	allowAdditionalProperties(s.Items)
	allowAdditionalProperties(s.Not)
	for _, list := range [][]*huma.Schema{s.AllOf, s.AnyOf, s.OneOf} {
		for _, sub := range list {
			allowAdditionalProperties(sub)
		}
	}
}
