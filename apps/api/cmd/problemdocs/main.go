// Command problemdocs writes docs/problems.md, the catalogue of problem types (ADR-0025). Every
// problem type URI points at a heading of that file, so the URI a client receives opens the
// documentation of its problem, as RFC 9457 asks of a type that is a locator. `just generate` runs
// it with CGO_ENABLED=0, like cmd/openapi: the TigerBeetle results come from a plain list, not
// from the cgo client.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"net/http"
	"os"

	bookkeepingdto "github.com/wilfriedago/tigerbeetle-platform/apps/api/internal/modules/bookkeeping/interfaces/dto"
	"github.com/wilfriedago/tigerbeetle-platform/apps/api/internal/platform/problem"
)

func main() {
	out := flag.String("out", "", "file to write the catalogue to; standard output when empty")
	flag.Parse()

	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "problemdocs:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	doc, err := build()
	if err != nil {
		return err
	}
	if out == "" {
		_, err = os.Stdout.Write(doc)
		return err
	}
	if err := os.WriteFile(out, doc, 0o644); err != nil { //nolint:gosec // the catalogue is a public file
		return fmt.Errorf("write %s: %w", out, err)
	}
	return nil
}

const intro = `# Problem types

<!-- Generated by cmd/problemdocs from the Go catalogue (ADR-0025); do not edit. -->

Every error the API answers is an RFC 9457 problem: an ` + "`application/problem+json`" + ` body with
` + "`type`" + `, ` + "`title`" + `, ` + "`status`" + `, and usually ` + "`detail`" + `, ` + "`instance`" + ` and ` + "`requestId`" + `.
GraphQL errors, gRPC statuses and broker RPC replies carry the same members. The ` + "`type`" + ` is
the URL of the problem's entry below; it is the same in every deployment, so clients switch on it.
A problem the HTTP status describes on its own, such as an unknown route (404), a wrong method
(405), an oversized body (413) or a fault of the service (500), has the type ` + "`about:blank`" + `
and the status phrase as its title.

`

const tigerBeetleIntro = `## TigerBeetle results

A posting TigerBeetle declines for a reason the platform does not name itself is reported under
the name of its result, the dashes standing for underscores. Most of these mean a request the
API should have refused first; report one as a bug.

`

// build renders the catalogue: the platform's problem types, then the TigerBeetle results.
func build() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(intro)
	seen := map[string]bool{}
	for _, d := range problem.Definitions() {
		if err := write(&b, "##", d, seen); err != nil {
			return nil, err
		}
	}
	b.WriteString(tigerBeetleIntro)
	for _, d := range bookkeepingdto.ProblemTypes() {
		if err := write(&b, "###", d, seen); err != nil {
			return nil, err
		}
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n'), nil
}

// write renders one entry under a heading that is its reason, which GitHub turns into the
// fragment of its type URI.
func write(b *bytes.Buffer, heading string, d problem.Definition, seen map[string]bool) error {
	if seen[d.Reason] {
		return fmt.Errorf("problem type %q is defined twice", d.Reason)
	}
	seen[d.Reason] = true
	fmt.Fprintf(b, "%s %s\n\n", heading, d.Reason)
	fmt.Fprintf(b, "- Type: `%s`\n", d.Type())
	fmt.Fprintf(b, "- Title: %s\n", d.Title)
	fmt.Fprintf(b, "- Status: %d %s\n\n", d.Status, http.StatusText(d.Status))
	fmt.Fprintf(b, "%s\n\n", d.Description)
	return nil
}
