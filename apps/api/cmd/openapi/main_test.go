package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestBuildIsByteStable(t *testing.T) {
	t.Parallel()
	first, err := build()
	if err != nil {
		t.Fatal(err)
	}
	second, err := build()
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("two builds of the spec differ")
	}
	if !strings.HasPrefix(string(first), "# Generated by cmd/openapi") {
		t.Fatalf("spec does not start with the generated header: %.80s", first)
	}
	if n := strings.Count(string(first), "operationId:"); n != 35 {
		t.Fatalf("spec declares %d operations, want 35", n)
	}
}

func TestRunWritesTheFile(t *testing.T) {
	t.Parallel()
	out := filepath.Join(t.TempDir(), "openapi.yaml")
	if err := run(out); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	want, err := build()
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("written file differs from the built spec")
	}
}
