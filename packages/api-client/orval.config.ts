import { defineConfig, defineTransformer } from 'orval'

// The generated client of ADR-0019: one module per OpenAPI tag under src/gen, every request sent
// through src/client/fetcher.ts. Run with `just generate`; never edit src/gen.

const methods = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'] as const

// The fetch layer sends X-Request-Id and X-Organization on every call (the organization from the
// client's configuration, ADR-0026), so the generated functions do not take them as arguments;
// the Idempotency-Key of the five money writes stays a typed, required header.
const fetchLayerHeaders = new Set(['X-Request-Id', 'X-Organization'])

const withoutFetchLayerHeaders = defineTransformer((spec) => {
  for (const item of Object.values(spec.paths ?? {})) {
    for (const method of methods) {
      const operation = item?.[method]
      if (operation?.parameters) {
        operation.parameters = operation.parameters.filter((p) => !('name' in p) || !fetchLayerHeaders.has(p.name))
      }
    }
  }
  return spec
})

export default defineConfig({
  api: {
    input: {
      target: '../openapi/openapi.yaml',
      override: { transformer: withoutFetchLayerHeaders }
    },
    output: {
      mode: 'tags-split',
      target: './src/gen/api.ts',
      schemas: './src/gen/model',
      client: 'fetch',
      clean: true,
      // Header parameters become a typed argument: a money write without its Idempotency-Key does
      // not compile.
      headers: true,
      // Addresses hold colons and patterns may be "*": every path parameter is encoded.
      urlEncodeParameters: true,
      override: {
        header: () => ['Generated by orval from packages/openapi/openapi.yaml (ADR-0019). Do not edit.'],
        mutator: { path: './src/client/fetcher.ts', name: 'fetcher' },
        fetch: { includeHttpResponseReturnType: false },
        operations: {
          getReadiness: { mutator: { path: './src/client/fetcher.ts', name: 'readinessFetcher' } }
        }
      }
    }
  }
})
